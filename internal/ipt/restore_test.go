// A mangle table as the firmware leaves it: its own chains, a jump of an
// earlier HyRouter in the middle, a chain HyRouter no longer has.
const savedMangle = `# Generated by iptables-save v1.4.21
*mangle
:PREROUTING ACCEPT [10:600]
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
:_NDM_POLICY - [0:0]
:HYR_PRE - [0:0]
:HYR_LAN - [0:0]
:HYR_OLD - [0:0]
-A PREROUTING -j _NDM_POLICY
-A PREROUTING -j HYR_PRE
-A POSTROUTING -j HYR_OLD
-A HYR_PRE -i br0 -g HYR_LAN
-A HYR_OLD -j RETURN
COMMIT
`

func TestParseSave(t *testing.T) {
	s := parseSave(savedMangle)
	if len(s.chains) != 9 || s.chains[5] != "_NDM_POLICY" {
		t.Errorf("chains %v", s.chains)
	}
	if got := s.rules["PREROUTING"]; len(got) != 2 || got[1] != "-j HYR_PRE" {
		t.Errorf("PREROUTING %q", got)
	}
	if s.jumps("PREROUTING", "HYR_PRE") != 1 || s.jumps("POSTROUTING", "HYR_PRE") != 0 {
		t.Error("jumps")
	}
	// The firmware's chain decides first: not hooked.
	if s.hooked("PREROUTING", "HYR_PRE") {
		t.Error("hooked behind the firmware's rule")
	}
	if !s.owns(OwnerRoute) || s.owns(OwnerGuard) {
		t.Error("owns")
	}
}

func TestRestoreInput(t *testing.T) {
	tb := Table{Family: 4, Name: "mangle", Chains: []string{"HYR_PRE", "HYR_LAN"},
		Rules: []string{"-A HYR_PRE -i br0 -g HYR_LAN", "# Всё остальное", "-A HYR_LAN -j RETURN"},
		Hooks: []Hook{{"PREROUTING", "HYR_PRE"}}}
	got := restoreInput(OwnerRoute, tb, parseSave(savedMangle))
	want := `*mangle
:HYR_PRE - [0:0]
:HYR_LAN - [0:0]
-A HYR_PRE -i br0 -g HYR_LAN
# Всё остальное
-A HYR_LAN -j RETURN
-D POSTROUTING -j HYR_OLD
-D PREROUTING -j HYR_PRE
-I PREROUTING 1 -j HYR_PRE
-F HYR_OLD
-X HYR_OLD
COMMIT
`
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
	// The guard's chains are not the routing's to remove.
	withGuard := strings.Replace(savedMangle, ":HYR_OLD - [0:0]", ":HYR_OLD - [0:0]\n:HYRG_FWD - [0:0]", 1)
	if got := restoreInput(OwnerRoute, tb, parseSave(withGuard)); strings.Contains(got, "HYRG_") {
		t.Errorf("the routing touched the guard:\n%s", got)
	}
	// Removing: every chain and hook of the owner goes.
	rm := removeInput(OwnerRoute, "mangle", parseSave(savedMangle))
	for _, l := range []string{"-D PREROUTING -j HYR_PRE", "-D POSTROUTING -j HYR_OLD", "-F HYR_LAN", "-X HYR_PRE", "-X HYR_OLD"} {
		if !strings.Contains(rm, l+"\n") {
			t.Errorf("removal lacks %q:\n%s", l, rm)
		}
	}
	if strings.Contains(rm, "_NDM_") || strings.Contains(rm, "-I ") {
		t.Errorf("removal touches the firmware's or adds:\n%s", rm)
	}
}

func TestHealthy(t *testing.T) {
	tb := Table{Family: 4, Name: "mangle", Chains: []string{"HYR_PRE", "HYR_LAN"}, Hooks: []Hook{{"PREROUTING", "HYR_PRE"}}}
	good := `*mangle
:PREROUTING ACCEPT [0:0]
:HYR_PRE - [0:0]
:HYR_LAN - [0:0]
:_NDM_POLICY - [0:0]
-A PREROUTING -j HYRG_X
-A PREROUTING -j HYR_PRE
-A PREROUTING -j _NDM_POLICY
COMMIT
`
	if !parseSave(good).healthy(tb) {
		t.Error("a healthy table is not")
	}
	for name, s := range map[string]string{
		"behind the firmware": savedMangle,
		"chain gone":          strings.Replace(good, ":HYR_LAN - [0:0]\n", "", 1),
		"hook gone":           strings.Replace(good, "-A PREROUTING -j HYR_PRE\n", "", 1),
		"hook twice":          strings.Replace(good, "-A PREROUTING -j _NDM_POLICY", "-A PREROUTING -j HYR_PRE", 1),
	} {
		if parseSave(s).healthy(tb) {
			t.Errorf("%s: healthy", name)
		}
	}
}

func TestIpsetInput(t *testing.T) {
	got := ipsetInput([]Set{
		{Name: "skip4", Net: true, Family: 4, Elems: []string{"10.0.0.0/8", "192.168.0.0/16"}},
		{Name: "r1_dns6", Family: 6, Timeout: true},
	})
	want := `create hyr_skip4_t hash:net family inet maxelem 262144
flush hyr_skip4_t
add hyr_skip4_t 10.0.0.0/8
add hyr_skip4_t 192.168.0.0/16
create hyr_skip4 hash:net family inet maxelem 262144
swap hyr_skip4_t hyr_skip4
destroy hyr_skip4_t
create hyr_r1_dns6 hash:ip family inet6 timeout 3600
flush hyr_r1_dns6
`
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
	if n := tmpName("hyr_0123456789012345678901234567"); len(n) > 31 {
		t.Errorf("tmpName %q is too long", n)
	}
}

func TestHookFile(t *testing.T) {
	rules, hooks := hookFile(Table{Family: 6, Name: "filter", Chains: []string{"HYR_FWD", "HYR_IN"},
		Rules: []string{"-A HYR_FWD -j DROP"}, Hooks: []Hook{{"FORWARD", "HYR_FWD"}, {"INPUT", "HYR_IN"}}})
	if rules != "*filter\n:HYR_FWD - [0:0]\n:HYR_IN - [0:0]\n-A HYR_FWD -j DROP\nCOMMIT\n" {
		t.Errorf("rules:\n%s", rules)
	}
	if hooks != "FORWARD HYR_FWD\nINPUT HYR_IN\n" {
		t.Errorf("hooks:\n%s", hooks)
	}
}
